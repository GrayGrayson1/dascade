/** Build merged horizontal-run rectangles per color from an art grid. */
export function artToRects(rows: readonly string[]): Array<{ x: number; y: number; w: number; color: string }> {
  const rects: Array<{ x: number; y: number; w: number; color: string }> = [];
  rows.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      const ch = row[x] as string;
      if (ch === '.' || ch === ' ') {
        x++;
        continue;
      }
      let end = x + 1;
      while (end < row.length && row[end] === ch) end++;
      rects.push({ x, y, w: end - x, color: ch });
      x = end;
    }
  });
  return rects;
}
