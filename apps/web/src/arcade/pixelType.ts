export const CAP_ROWS = 7;

export function pixelGlyph(ch: string): string[] {
  return LOWER[ch] ?? CAPS[ch] ?? CAPS[ch.toUpperCase()] ?? CAPS['?']!;
}

export interface PixelLayout {
  /** Filled cells as [x, y]. */
  cells: Array<[number, number]>;
  width: number;
  /** 7, or 9 when the text has descenders. */
  rows: number;
}

/** Lays out `text` on the cell grid (1-cell letter spacing). */
export function layoutPixelText(text: string): PixelLayout {
  const cells: Array<[number, number]> = [];
  let x = 0;
  let rows = CAP_ROWS;
  const chars = [...text];
  chars.forEach((ch, i) => {
    const g = pixelGlyph(ch);
    rows = Math.max(rows, g.length);
    const w = g[0]!.length;
    for (let r = 0; r < g.length; r++) for (let c = 0; c < w; c++) if (g[r]![c] === '#') cells.push([x + c, r]);
    x += w + (i < chars.length - 1 ? 1 : 0);
  });
  return { cells, width: x, rows };
}
