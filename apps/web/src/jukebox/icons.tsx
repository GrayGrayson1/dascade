export type GlyphName = keyof typeof GLYPHS;

function rects(rows: readonly string[]): Array<{ x: number; y: number; w: number }> {
  const out: Array<{ x: number; y: number; w: number }> = [];
  rows.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      if (row[x] === '#') {
        let w = 1;
        while (row[x + w] === '#') w++;
        out.push({ x, y, w });
        x += w;
      } else x++;
    }
  });
  return out;
}

const CACHE = new Map<GlyphName, Array<{ x: number; y: number; w: number }>>();

export function Glyph({
  name,
  size = 16,
  className,
  style,
}: {
  name: GlyphName;
  size?: number;
  className?: string;
  style?: CSSProperties;
}) {
  let r = CACHE.get(name);
  if (!r) {
    r = rects(GLYPHS[name]);
    CACHE.set(name, r);
  }
  return (
    <svg
      className={className ? `jb-glyph ${className}` : 'jb-glyph'}
      viewBox="0 0 12 12"
      width={size}
      height={size}
      shapeRendering="crispEdges"
      aria-hidden
      focusable="false"
      style={style}
    >
      {r.map((q, i) => (
        <rect key={i} x={q.x} y={q.y} width={q.w} height={1} fill="currentColor" />
      ))}
    </svg>
  );
}
